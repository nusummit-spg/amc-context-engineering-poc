<#
.SYNOPSIS
  Start/stop DISPOSABLE local PostgreSQL and Neo4j for AMC Wave 3.1 qualification WITHOUT Docker.

.DESCRIPTION
  Everything binds to 127.0.0.1 and lives under $env:AMC_LOCAL_SERVICES_ROOT (default C:\amc-work\local-services).
  Never point this at real data. Passwords are generated by you and kept in local.env.ps1 beside the data;
  they are never written to Git.

  ONE-TIME SETUP (what was done for the Wave 3.1 validation; versions pinned, verify the checksums):
    1. PostgreSQL 16 binaries:   pip install pgserver     (wheel with embedded PostgreSQL 16.2)
         set AMC_PG_BIN to ...\site-packages\pgserver\pginstall\bin
         initdb -D <root>\pgdata -U amc_qa -E UTF8 --auth=scram-sha-256 --pwfile=<file with your password>
    2. Java 17:                  Eclipse Temurin 17 zip from adoptium.net, verify the SHA-256 on the release page
         extract to <root>\jdk
    3. Neo4j 5.24 Community:     neo4j-community-5.24.2-windows.zip from dist.neo4j.org, verify against the
         published .sha256; extract to <root>\neo4jx; then in conf\neo4j.conf set
           server.default_listen_address=127.0.0.1
           server.bolt.listen_address=127.0.0.1:57687
           server.http.listen_address=127.0.0.1:57474
           server.https.enabled=false
           server.jvm.additional=-Djdk.net.unixdomain.tmpdir=C:/amc-work/tmp     (see KNOWN ISSUE)
         neo4j-admin dbms set-initial-password <your password>   (before the first start)

  KNOWN ISSUE (Windows 11 build 26200): the JDK's internal selector pipe uses an AF_UNIX socket in the temp
  directory, and connecting to it fails under the user's AppData\Local\Temp ("Unable to establish loopback
  connection"). Pointing jdk.net.unixdomain.tmpdir at a short folder on a normal NTFS path (e.g. C:\amc-work\tmp)
  fixes it. Neo4j will not start without this on an affected machine.

.PARAMETER Action
  Start (default) | Stop | Status | KillPostgres | KillNeo4j   (the Kill* actions are for outage drills)
#>
param([ValidateSet('Start', 'Stop', 'Status', 'KillPostgres', 'KillNeo4j')][string]$Action = 'Start')

$root = if ($env:AMC_LOCAL_SERVICES_ROOT) { $env:AMC_LOCAL_SERVICES_ROOT } else { 'C:\amc-work\local-services' }
$pgBin = $env:AMC_PG_BIN
if (-not $pgBin) { throw 'Set AMC_PG_BIN to the PostgreSQL bin directory (see the setup notes in this file).' }
$pgData = Join-Path $root 'pgdata'
$nh = Join-Path $root 'neo4jx\neo4j-community-5.24.2'
$jh = (Get-ChildItem (Join-Path $root 'jdk') -Directory | Select-Object -First 1).FullName

function Test-Port($p) { [bool](Get-NetTCPConnection -LocalPort $p -State Listen -ErrorAction SilentlyContinue) }

switch ($Action) {
    'Status' { "postgres 55432 up: $(Test-Port 55432)   neo4j 57687 up: $(Test-Port 57687)"; return }
    { $_ -in 'Stop', 'KillPostgres' } { & "$pgBin\pg_ctl.exe" stop -D $pgData -m fast 2>&1 | Out-Null }
}
switch ($Action) {
    { $_ -in 'Stop', 'KillNeo4j' } {
        Get-Process java -ErrorAction SilentlyContinue | Where-Object { $_.Path -like "$root*" } | Stop-Process -Force
    }
}
if ($Action -ne 'Start') { 'done'; return }

if (-not (Test-Port 55432)) {
    Remove-Item (Join-Path $pgData 'postmaster.pid') -ErrorAction SilentlyContinue
    Start-Process -FilePath "$pgBin\postgres.exe" -ArgumentList @('-D', $pgData, '-p', '55432', '-c', 'listen_addresses=127.0.0.1') `
        -WindowStyle Hidden -RedirectStandardError "$root\pg.err.log" -RedirectStandardOutput "$root\pg.out.log" | Out-Null
}
if (-not (Test-Port 57687)) {
    $env:JAVA_HOME = $jh
    Start-Process -FilePath "$nh\bin\neo4j.bat" -ArgumentList 'console' -WorkingDirectory $nh -WindowStyle Hidden `
        -RedirectStandardOutput "$root\neo4j.out.log" -RedirectStandardError "$root\neo4j.err.log" | Out-Null
}
for ($i = 0; $i -lt 30; $i++) {
    Start-Sleep -Seconds 3
    if ((Test-Port 55432) -and (Test-Port 57687)) { break }
}
"postgres 55432 up: $(Test-Port 55432)   neo4j 57687 up: $(Test-Port 57687)"
