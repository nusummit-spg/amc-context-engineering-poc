"""Static audit: which frontend API call sites the verified pilot perimeter would deny.

This is a SOURCE-LEVEL audit of call sites found by pattern matching. It does not run
the UI and is not browser evidence (G7 stays BLOCKED until a real browser run exists).

    python -m tools.amc_release.frontend_pilot_audit31 --write remediation/wave3_1/FRONTEND_PILOT_COMPATIBILITY.md
    python -m tools.amc_release.frontend_pilot_audit31 --check remediation/wave3_1/FRONTEND_PILOT_COMPATIBILITY.md
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SRC = REPO / "mf-context-engine" / "src"
sys.path.insert(0, str(REPO / "backend"))
from app.api.pilot_perimeter31 import is_pilot_route_allowed  # noqa: E402  (pure, imports only os)

# request("/x", ...) / authRequest("/x", ...) / fetch(`${API_BASE}/x`, ...)
_CALL = re.compile(
    r"(?P<fn>request|authRequest|fetch)\(\s*(?P<q>[`\"'])(?P<path>[^`\"']*)(?P=q)", re.S)
_METHOD = re.compile(r"method\s*:\s*[\"'`](?P<m>[A-Za-z]+)[\"'`]")
_TEMPLATE = re.compile(r"\$\{[^}]*\}")

# Calls that are the core pilot journey; the test asserts these stay allowed.
CORE_PILOT_CALLS = (
    ("POST", "/api/auth/login"), ("POST", "/api/auth/logout"), ("GET", "/api/auth/me"),
    ("POST", "/api/query"), ("POST", "/api/query/stream"),
    ("POST", "/api/chat"), ("POST", "/api/chat/stream"),
)


def _normalize(fn: str, raw: str) -> str | None:
    path = raw
    if fn == "fetch":
        if not path.startswith("${API_BASE}"):
            return None
        path = path[len("${API_BASE}"):]
    # An unbalanced "${" means the capture stopped inside a nested template literal
    # (for example `?${qs}`); everything from there on is query-string, not path.
    start = path.find("${")
    while start != -1:
        end = path.find("}", start)
        if end == -1:
            path = path[:start]
            break
        start = path.find("${", end)
    path = re.sub(r"/\$\{[^}]*\}", "/x", path)   # a whole path segment is dynamic
    path = _TEMPLATE.sub("", path)               # a suffix such as ${query} is query-string
    path = path.split("?")[0].split("#")[0]
    if not path.startswith("/"):
        return None
    return path if path.startswith("/api/") else "/api" + path


def collect_calls(src: Path = SRC) -> list[dict]:
    calls = []
    for file in sorted(list(src.rglob("*.js")) + list(src.rglob("*.jsx"))):
        if file.name.endswith(".test.js"):
            continue
        text = file.read_text(encoding="utf-8", errors="replace")
        for match in _CALL.finditer(text):
            path = _normalize(match.group("fn"), match.group("path"))
            if path is None:
                continue
            window = text[match.end(): match.end() + 400]
            nxt = _CALL.search(window)
            if nxt:
                window = window[: nxt.start()]
            m = _METHOD.search(window)
            line = text.count("\n", 0, match.start()) + 1
            calls.append({"file": file.relative_to(REPO).as_posix(), "line": line,
                          "method": (m.group("m").upper() if m else "GET"), "path": path})
    return calls


def audit(calls: list[dict] | None = None) -> dict:
    calls = collect_calls() if calls is None else calls
    seen, allowed, denied = set(), [], []
    for c in calls:
        c = dict(c, allowed=is_pilot_route_allowed(c["method"], c["path"]))
        (allowed if c["allowed"] else denied).append(c)
        seen.add((c["method"], c["path"]))
    return {"calls": calls, "allowed": allowed, "denied": denied, "distinct": sorted(seen)}


def _group(rows: list[dict]) -> dict[tuple[str, str], list[str]]:
    grouped: dict[tuple[str, str], list[str]] = {}
    for r in rows:
        grouped.setdefault((r["method"], r["path"]), []).append(f"{r['file']}:{r['line']}")
    return grouped


def render(result: dict | None = None) -> str:
    result = audit() if result is None else result
    out = [
        "# Frontend call sites vs verified pilot perimeter",
        "",
        "Generated by `python -m tools.amc_release.frontend_pilot_audit31 --write <this file>`.",
        "Regenerate it after changing the frontend or the pilot allowlist; the test suite fails on a stale copy.",
        "",
        "**Scope and limits.** Static pattern match over `mf-context-engine/src`; it finds call sites, not",
        "which ones run on a given screen. It is not browser evidence: gate G7 stays BLOCKED until the pilot",
        "UI has been exercised in a real browser against a real enforce-mode backend.",
        "",
        "## Allowed in the pilot",
        "",
        "| Method | Path | Call sites |",
        "|---|---|---|",
    ]
    for (method, path), where in sorted(_group(result["allowed"]).items()):
        out.append(f"| {method} | `{path}` | {', '.join(where)} |")
    out += ["", "## Denied by the pilot perimeter (503)", "",
            "These would fail in `AMC_VERIFIED_SERVING_MODE=enforce`. Each needs the UI to hide the control or",
            "handle the denial quietly; a polling loop against a denied route is a defect.", "",
            "| Method | Path | Call sites |", "|---|---|---|"]
    for (method, path), where in sorted(_group(result["denied"]).items()):
        out.append(f"| {method} | `{path}` | {', '.join(where)} |")
    out += [
        "", "## What the pilot build does about the denied calls", "",
        "With `VITE_AMC_PILOT_MODE=true` the API client (`services/api.js`) refuses every call outside the",
        "allowlist in `utils/pilotSources.js` before any network request, so the denied calls above produce no",
        "503 round trips and no console errors. The sidebar shows Chat only: Compare, Analytics, Admin, My",
        "Feedback, Feedback triage and every Compliance Module page are hidden, because those pages call denied",
        "routes and, when a call fails, some of them fall back to built-in sample figures that would be shown",
        "as if they were real. A Python test (`test_pilot_allowlist_parity31.py`) keeps the JS allowlist equal",
        "to the backend perimeter.",
        "", "## Source-document links", "",
        "Citation components link to `/api/files/...`, which the pilot denies on purpose. With the build flag",
        "`VITE_AMC_PILOT_MODE=true` they render non-clickable provenance instead (see",
        "`mf-context-engine/src/utils/pilotSources.js`). The flag is off by default, so the non-pilot app is unchanged.",
        "",
        f"Distinct denied calls: {len(_group(result['denied']))}; allowed: {len(_group(result['allowed']))}.",
        "",
    ]
    return "\n".join(out)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", type=Path)
    group.add_argument("--check", type=Path)
    args = parser.parse_args(argv)
    text = render()
    if args.write:
        args.write.parent.mkdir(parents=True, exist_ok=True)
        args.write.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {args.write}")
        return 0
    if args.check.read_text(encoding="utf-8") != text:
        print("STALE: regenerate with --write and review the diff", file=sys.stderr)
        return 2
    print("frontend compatibility report OK")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
